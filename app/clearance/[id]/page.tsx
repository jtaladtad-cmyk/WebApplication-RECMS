import type { Metadata } from "next";
import { notFound } from "next/navigation";
import { isStaff, requireUser } from "@/lib/auth";
import { get } from "@/lib/db";
import { getProposal } from "@/lib/recms";
import { fmtDate, label } from "@/lib/format";
import { PrintButton } from "./PrintButton";

export const metadata: Metadata = { title: "Ethics clearance" };

export default async function ClearancePage({ params }: { params: Promise<{ id: string }> }) {
  const user = await requireUser();
  const p = await getProposal(Number((await params).id));
  if (!p || (p.researcher_id !== user.user_id && !isStaff(user))) notFound();
  const c = await get<{ clearance_no: string; issued_at: string; valid_until: string; issued_by_name: string }>(
    `SELECT c.clearance_no, c.issued_at, c.valid_until, u.full_name AS issued_by_name
       FROM ethics_clearances c JOIN users u ON u.user_id = c.issued_by WHERE c.proposal_id = ?`,
    p.proposal_id,
  );
  if (!c) notFound();

  return (
    <div className="min-h-screen bg-slate-100 py-10 print:bg-white print:py-0">
      <div className="no-print mx-auto mb-4 flex max-w-[820px] justify-between px-4">
        <a href={`/proposals/${p.proposal_id}`} className="link text-sm">← Back to proposal</a>
        <PrintButton />
      </div>
      <article className="mx-auto max-w-[820px] bg-white p-14 shadow print:shadow-none">
        <header className="border-b-4 border-double border-brand-800 pb-5 text-center">
          <div className="text-xl font-bold uppercase tracking-wide text-brand-900">Notre Dame of Dadiangas University</div>
          <div className="text-sm text-slate-600">Marist Avenue, General Santos City</div>
          <div className="mt-2 text-sm font-semibold text-slate-700">Research and Publication Center · Ethics Research Committee</div>
        </header>

        <h1 className="mt-8 text-center text-3xl font-bold tracking-widest text-slate-900">ETHICS CLEARANCE</h1>
        <div className="mt-1 text-center font-mono text-sm text-slate-600">No. {c.clearance_no}</div>

        <p className="mt-10 leading-7 text-slate-800">
          This is to certify that the research protocol entitled
        </p>
        <p className="my-4 text-center text-lg font-semibold italic leading-7">&ldquo;{p.title}&rdquo;</p>
        <p className="leading-7 text-slate-800">
          submitted by <b>{p.researcher_name}</b>
          {p.co_researchers ? <> with <b>{p.co_researchers}</b></> : null} of the <b>{p.college}</b>, under ERC reference
          number <b>{p.reference_no}</b>, has been reviewed by the Ethics Research Committee through{" "}
          <b>{label(p.review_type).toLowerCase()}</b> review and is hereby <b>APPROVED</b>. The researcher(s) may proceed
          with the study in accordance with the approved protocol (version {p.current_version}).
        </p>
        <p className="mt-4 leading-7 text-slate-800">
          Any amendment to the protocol must be submitted to the ERC for approval prior to implementation. Adverse events
          and protocol deviations must be reported promptly. This clearance is valid until <b>{fmtDate(c.valid_until)}</b>;
          continuing review is required for studies extending beyond this date.
        </p>

        <div className="mt-10 grid grid-cols-2 gap-6 text-sm">
          <div>
            <div className="text-slate-500">Date issued</div>
            <div className="font-semibold">{fmtDate(c.issued_at)}</div>
          </div>
          <div>
            <div className="text-slate-500">Valid until</div>
            <div className="font-semibold">{fmtDate(c.valid_until)}</div>
          </div>
        </div>

        <div className="mt-20 grid grid-cols-2 gap-12 text-center text-sm">
          <div>
            <div className="border-t border-slate-800 pt-1 font-semibold">{c.issued_by_name}</div>
            <div className="text-slate-600">ERC Secretariat</div>
          </div>
          <div>
            <div className="border-t border-slate-800 pt-1 font-semibold">&nbsp;</div>
            <div className="text-slate-600">ERC Chairperson</div>
          </div>
        </div>
        <footer className="mt-14 border-t border-slate-200 pt-3 text-center text-[11px] text-slate-500">
          System-generated by RECMS · Verify this clearance with the ERC using No. {c.clearance_no}
        </footer>
      </article>
    </div>
  );
}
